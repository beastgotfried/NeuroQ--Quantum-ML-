    pdf.add_page()
    
    # Title
    pdf.set_font("Arial", 'B', 20)
    pdf.cell(0, 10, 'NeuroQ Diagnostic Report', ln=True, align='C')
    pdf.ln(10)
    
    # Patient Info
    pdf.set_font("Arial", 'B', 12)
    pdf.cell(0, 10, f'Patient ID: {patient_id}', ln=True)
    pdf.cell(0, 10, f'Date: {time.strftime("%Y-%m-%d %H:%M:%S")}', ln=True)
    pdf.ln(5)

    # Diagnosis Box
    pdf.set_fill_color(230, 230, 230)
    pdf.cell(0, 10, f' Diagnosis: {result}', ln=True, fill=True)
    pdf.cell(0, 10, f' AI Confidence: {confidence}', ln=True, fill=True)
    pdf.ln(10)

    # Insert Image (Save temp file)
    with tempfile.NamedTemporaryFile(delete=False, suffix=".png") as temp_img:
        pil_image.save(temp_img.name)
        # Center image (approx 100mm width)
        pdf.image(temp_img.name, x=55, w=100)
        temp_img_path = temp_img.name
    
    # Clean up temp file later
    os.remove(temp_img_path)
    pdf.ln(10)

    # Detailed Findings
    pdf.set_font("Arial", 'B', 14)
    pdf.cell(0, 10, 'Clinical Findings & Analysis', ln=True)
    pdf.set_font("Arial", '', 11)
    
    for item in findings:
        pdf.multi_cell(0, 8, f"- {item}")
    
    pdf.ln(5)
    pdf.set_font("Arial", 'I', 10)
    pdf.multi_cell(0, 10, "Disclaimer: This report was generated by a Hybrid Quantum Neural Network (NeuroQ) and should be verified by a certified radiologist.")

    return pdf.output(dest='S').encode('latin-1')

